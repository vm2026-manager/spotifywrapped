const formatNumber = (value) => new Intl.NumberFormat("da-DK").format(value);

function getFilteredData() {
  if (selectedYear === "all") return archiveData;
  return archiveData.filter((item) => String(item.year) === String(selectedYear));
}

function getAllSongRows(data = getFilteredData()) {
  return data.flatMap((yearData) =>
    yearData.songs.map((song) => ({
      year: yearData.year,
      ...song
    }))
  );
}

function normalize(value) {
  return String(value || "").toLowerCase().trim();
}

function getPrimaryArtist(artistText) {
  return artistText.split(",")[0].trim();
}

function average(values) {
  return values.reduce((sum, value) => sum + value, 0) / values.length;
}

function getArtistOccurrences() {
  const map = new Map();

  archiveData.forEach((yearData) => {
    yearData.songs.forEach((song) => {
      const primary = getPrimaryArtist(song.artist);
      const key = normalize(primary);

      if (!map.has(key)) {
        map.set(key, {
          name: primary,
          years: new Set(),
          ranks: [],
          songs: []
        });
      }

      const entry = map.get(key);
      entry.years.add(yearData.year);
      entry.ranks.push(song.rank);
      entry.songs.push(song.title);
    });
  });

  return Array.from(map.values())
    .map((entry) => ({
      ...entry,
      years: Array.from(entry.years).sort((a, b) => a - b)
    }))
    .filter((entry) => entry.years.length > 1 || entry.ranks.length > 2)
    .sort((a, b) => b.years.length - a.years.length || average(a.ranks) - average(b.ranks));
}

function getSongOccurrences() {
  const map = new Map();

  archiveData.forEach((yearData) => {
    yearData.songs.forEach((song) => {
      const key = normalize(song.title);

      if (!map.has(key)) {
        map.set(key, {
          title: song.title,
          artists: new Set(),
          years: new Set(),
          ranks: []
        });
      }

      const entry = map.get(key);
      entry.artists.add(song.artist);
      entry.years.add(yearData.year);
      entry.ranks.push(song.rank);
    });
  });

  return Array.from(map.values())
    .map((entry) => ({
      ...entry,
      artists: Array.from(entry.artists),
      years: Array.from(entry.years).sort((a, b) => a - b)
    }))
    .filter((entry) => entry.years.length > 1)
    .sort((a, b) => b.years.length - a.years.length || average(a.ranks) - average(b.ranks));
}

function getMostRepeatedArtist() {
  return getArtistOccurrences()[0];
}

function getMinutesData() {
  return archiveData.filter((item) => typeof item.minutes === "number");
}

function updateSummary() {
  const data = getFilteredData();
  const minutesData = data.filter((item) => typeof item.minutes === "number");
  const allMinutesData = getMinutesData();
  const total = minutesData.reduce((sum, item) => sum + item.minutes, 0);
  const topYear = minutesData.length
    ? [...minutesData].sort((a, b) => b.minutes - a.minutes)[0]
    : [...allMinutesData].sort((a, b) => b.minutes - a.minutes)[0];

  const repeatedArtist = getMostRepeatedArtist();

  document.getElementById("totalMinutes").textContent = total ? formatNumber(total) : "Ikke oplyst";
  document.getElementById("totalMinutesLabel").textContent =
    selectedYear === "all"
      ? "kendte Wrapped-minutter"
      : minutesData.length
        ? "Wrapped-minutter for valgt år"
        : "ingen minutdata for valgt år";

  document.getElementById("topYear").textContent = topYear ? topYear.year : "-";
  document.getElementById("topYearMinutes").textContent = topYear
    ? `${formatNumber(topYear.minutes)} minutter`
    : "Kun år med Wrapped-tal";

  document.getElementById("mostRepeatedArtist").textContent = repeatedArtist ? repeatedArtist.name : "-";
  document.getElementById("mostRepeatedArtistYears").textContent = repeatedArtist
    ? `${repeatedArtist.years.length} år: ${repeatedArtist.years.join(", ")}`
    : "-";

  const first = allMinutesData[0];
  const last = allMinutesData[allMinutesData.length - 1];
  const diff = first && last ? last.minutes - first.minutes : 0;
  document.getElementById("growthPill").textContent =
    first && last ? `${diff >= 0 ? "+" : ""}${formatNumber(diff)} min. siden ${first.year}` : "Wrapped-data";
}

