function renderHeatmap() {
  const container = document.getElementById("artistHeatmap");
  const artists = getArtistOccurrences().slice(0, 8).map((entry) => entry.name);

  const rows = archiveData.map((yearData) => {
    const primaryArtists = yearData.songs.map((song) => getPrimaryArtist(song.artist));

    const cells = artists.map((artist) => {
      const rank = primaryArtists.findIndex((name) => normalize(name) === normalize(artist)) + 1;
      const intensity = rank === 0 ? 0.06 : 0.22 + Math.max(0, 15 - rank) * 0.045;
      const title = rank === 0 ? `${artist}: ikke i aflæst top` : `${artist}: #${rank} i ${yearData.year}`;
      return `<div class="heatmap-cell" title="${title}" style="--intensity: ${intensity}"></div>`;
    }).join("");

    return `
      <div class="heatmap-row">
        <div class="heatmap-year">${yearData.year}</div>
        ${cells}
      </div>
    `;
  }).join("");

  const labels = `
    <div class="heatmap-labels">
      <div></div>
      ${artists.map((artist) => `<div class="heatmap-label">${artist}</div>`).join("")}
    </div>
  `;

  container.innerHTML = rows + labels;
}

function renderCompareControls() {
  const fromSelect = document.getElementById("fromYear");
  const toSelect = document.getElementById("toYear");

  const options = archiveData.map((item) => `<option value="${item.year}">${item.year}</option>`).join("");

  fromSelect.innerHTML = options;
  toSelect.innerHTML = options;

  fromSelect.value = "2017";
  toSelect.value = "2025";

  fromSelect.addEventListener("change", renderCompareCards);
  toSelect.addEventListener("change", renderCompareCards);

  renderCompareCards();
}

function renderCompareCards() {
  const fromYear = Number(document.getElementById("fromYear").value);
  const toYear = Number(document.getElementById("toYear").value);
  const from = archiveData.find((item) => item.year === fromYear);
  const to = archiveData.find((item) => item.year === toYear);
  const container = document.getElementById("compareCards");

  const minuteValue =
    typeof from.minutes === "number" && typeof to.minutes === "number"
      ? `${to.minutes - from.minutes >= 0 ? "+" : ""}${formatNumber(to.minutes - from.minutes)}`
      : "Ikke sammenligneligt";

  const cards = [
    {
      title: "Minutter",
      old: `${from.year}: ${typeof from.minutes === "number" ? formatNumber(from.minutes) : "Ikke oplyst"}`,
      value: minuteValue,
      newValue: `${to.year}: ${typeof to.minutes === "number" ? formatNumber(to.minutes) : "Ikke oplyst"}`
    },
    {
      title: "#1-sang",
      old: `${from.year}: ${from.topSong || "Ikke oplyst"}`,
      value: from.topSong === to.topSong ? "Samme" : "Skift",
      newValue: `${to.year}: ${to.topSong || "Ikke oplyst"}`
    },
    {
      title: "#1-kunstner",
      old: `${from.year}: ${from.topArtist || "Ikke oplyst"}`,
      value: from.topArtist === to.topArtist ? "Samme" : "Skift",
      newValue: `${to.year}: ${to.topArtist || "Ikke oplyst"}`
    },
    {
      title: "Genre/emne",
      old: `${from.year}: ${from.topGenre || from.podcastTopic || "Ikke oplyst"}`,
      value: (from.topGenre || from.podcastTopic) === (to.topGenre || to.podcastTopic) ? "Samme" : "Ændret",
      newValue: `${to.year}: ${to.topGenre || to.podcastTopic || "Ikke oplyst"}`
    },
    {
      title: "Data",
      old: `${from.year}: ${from.dataType}`,
      value: from.dataType === to.dataType ? "Samme type" : "Ny type",
      newValue: `${to.year}: ${to.dataType}`
    }
  ];

  container.innerHTML = cards.map((card) => `
    <article class="compare-card">
      <p class="section-label">${card.title}</p>
      <p class="old">${card.old}</p>
      <div class="value">${card.value}</div>
      <p class="old">${card.newValue}</p>
    </article>
  `).join("");
}

